fn deriv_doctor_writes_jpeg_still() {
    let (root, arch, hash, id) = seed_blob("jpeg", JPEG, "ada.jpg", "image/jpeg", "image");
    let issues = arch.doctor_issues().unwrap();
    assert!(
        !issues.iter().any(|i| i.contains("CAS blob missing")),
        "DERIV-DOCTOR-ORDER: {issues:?}"
    );
    let stills = stills_besides(&root, JPEG);
    assert_eq!(
        stills.len(),
        1,
        "DERIV-ADDR: doctor did not write a second CAS object"
    );
    assert!(
        std::fs::read(&stills[0])
            .unwrap()
            .starts_with(&[0xFF, 0xD8]),
        "DERIV-ADDR: jpeg still must be a JPEG"
    );
    let orig = cas_files(&root)
        .into_iter()
        .find(|p| std::fs::read(p).unwrap() == JPEG)
        .unwrap();
    assert_eq!(std::fs::read(orig).unwrap(), JPEG);
    let pointer = deriv_hash(&arch, id).expect("DERIV-TIE: pointer is null");
    assert_ne!(pointer, hash, "DERIV-TIE: pointer is the original hash");
    assert_eq!(schema_epoch(&arch), 1, "DERIV-EPOCH");
    let n: i64 = arch
        .conn
        .query_row("SELECT COUNT(*) FROM attachments", [], |r| r.get(0))
        .unwrap();
    assert_eq!(
        n, 1,
        "DERIV-ADDR: a still must not be a second attachment row"
    );
    let _ = std::fs::remove_dir_all(&root);
}

