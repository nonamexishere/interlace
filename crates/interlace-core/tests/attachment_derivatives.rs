fn tmp_root(label: &str) -> PathBuf {
    let n = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let seq = SEQ.fetch_add(1, Ordering::Relaxed);
    let p = std::env::temp_dir().join(format!(
        "il-deriv-{}-{}-{n}-{seq}",
        std::process::id(),
        label
    ));
    let _ = std::fs::remove_dir_all(&p);
    std::fs::create_dir_all(&p).unwrap();
    p
}

fn cas_files(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let cas = root.join("cas");
    if !cas.is_dir() {
        return out;
    }
    for a in std::fs::read_dir(&cas).unwrap() {
        let a = a.unwrap().path();
        if !a.is_dir() {
            continue;
        }
        for b in std::fs::read_dir(&a).unwrap() {
            let b = b.unwrap().path();
            if !b.is_dir() {
                continue;
            }
            for f in std::fs::read_dir(&b).unwrap() {
                let f = f.unwrap().path();
                if f.is_file() {
                    out.push(f);
                }
            }
        }
    }
    out.sort();
    out
}

fn has_deriv_column(arch: &Archive) -> bool {
    let mut stmt = arch.conn.prepare("PRAGMA table_info(attachments)").unwrap();
    let names: Vec<String> = stmt
        .query_map([], |r| r.get::<_, String>(1))
        .unwrap()
        .filter_map(Result::ok)
        .collect();
    names.iter().any(|n| n == "derivative_cas_hash")
}

fn deriv_hash(arch: &Archive, attachment_id: i64) -> Option<String> {
    assert!(
        has_deriv_column(arch),
        "DERIV-TIE: attachments has no derivative_cas_hash"
    );
    arch.conn
        .query_row(
            "SELECT derivative_cas_hash FROM attachments WHERE id = ?1",
            [attachment_id],
            |r| r.get(0),
        )
        .unwrap()
}

fn schema_epoch(arch: &Archive) -> i64 {
    arch.conn
        .query_row("SELECT schema_epoch FROM archive_meta", [], |r| r.get(0))
        .unwrap()
}

fn seed_blob(
    label: &str,
    bytes: &[u8],
    filename: &str,
    mime: &str,
    kind: &str,
) -> (PathBuf, Archive, String, i64) {
    let root = tmp_root(label);
    let arch = init_archive(&root).unwrap();
    arch.conn
        .execute(
            "INSERT INTO sources(kind, label, origin_path) VALUES ('gmail_mbox', 't', '/t.mbox')",
            [],
        )
        .unwrap();
    arch.conn
        .execute(
            "INSERT INTO import_runs(source_id, status) VALUES (1, 'done')",
            [],
        )
        .unwrap();
    arch.conn
        .execute(
            "INSERT INTO conversations(platform, kind, native_id) VALUES ('gmail', 'email_thread', 'g1')",
            [],
        )
        .unwrap();
    arch.conn
        .execute(
            "INSERT INTO messages(
                conversation_id, source_id, import_run_id, sent_at, sent_at_precision,
                kind, body_text, idempotency_key
             ) VALUES (1, 1, 1, '2024-01-01T00:00:00Z', 'second', 'text', 'hello', ?1)",
            [label],
        )
        .unwrap();
    let hash = arch.cas_put(bytes, Some(mime)).unwrap();
    arch.conn
        .execute(
            "INSERT INTO attachments(message_id, cas_hash, filename, mime, kind, omitted, missing)
             VALUES (1, ?1, ?2, ?3, ?4, 0, 0)",
            rusqlite::params![hash, filename, mime, kind],
        )
        .unwrap();
    (root, arch, hash, 1)
}

fn stills_besides(root: &Path, original: &[u8]) -> Vec<PathBuf> {
    cas_files(root)
        .into_iter()
        .filter(|p| std::fs::read(p).unwrap() != original)
        .collect()
}

fn assert_still_image(path: &Path) {
    let b = std::fs::read(path).unwrap();
    let jpeg = b.starts_with(&[0xFF, 0xD8]);
    let png = b.starts_with(&[0x89, 0x50, 0x4E, 0x47]);
    assert!(jpeg || png, "DERIV-ADDR: still is not a JPEG or PNG");
}

/// `load_from_memory` does not apply EXIF orientation. Callers must not either.
fn decoded_size(bytes: &[u8], id_tag: &str) -> (u32, u32) {
    let img = match image::load_from_memory(bytes) {
        Ok(img) => img,
        Err(err) => panic!("{id_tag}: load_from_memory failed: {err}"),
    };
    (img.width(), img.height())
}

